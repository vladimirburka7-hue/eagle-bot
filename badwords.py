_CYR = re.compile("[а-я]")
_HOMO = str.maketrans({"a": "а", "c": "с", "e": "е", "o": "о", "p": "р", "x": "х", "y": "у", "k": "к", "h": "н", "m": "м", "t": "т", "b": "б", "i": "и", "u": "и", "n": "п"})
_DIGITS = str.maketrans({"0": "о", "1": "и", "3": "з", "4": "ч", "6": "б", "@": "а", "$": "с"})
_ZERO = re.compile("[\u200b-\u200f\u2060\ufeff\u00ad]")
_INNER = re.compile(r"(?<=[\wа-яёa-z])[*.\-_'`´ʼ·•|/\\~+](?=[\wа-яёa-z])")
_WORD = re.compile(r"[a-zа-яё0-9@$]+")
_REPEAT = re.compile(r"(.)\1+")
_COMPILED = {}


def _compile(table):
    out = {}
    for category, items in table.items():
        out[category] = [re.compile(r"(?:%s)" % "|".join(items))] if items else []
    return out


_WORDS_RU = _compile(PATTERNS)
_WORDS_LAT = _compile(LATIN)
_PHRASES = {c: [re.compile(p) for p in items] for c, items in PHRASES.items()}


def clean(text: str) -> str:
    """Простой вид сообщения: нижний регистр, без ё, без невидимых символов и разделителей внутри слов."""
    text = _ZERO.sub("", (text or "").lower().replace("ё", "е"))
    return _INNER.sub("", text)


def collapse(word: str) -> str:
    return _REPEAT.sub(r"\1", word)


def tokens(text: str) -> list:
    """Слова сообщения в нескольких видах (с исправленной раскладкой и цифрами), плюс склейка «х у й»."""
    words = _WORD.findall(clean(text))
    variants = []
    for w in words:
        forms = {w}
        if _CYR.search(w):
            forms.add(w.translate(_HOMO).translate(_DIGITS))
        elif re.search("[a-z]", w) and re.search("[0-9@$]", w):
            forms.add(w.translate(_DIGITS))
        variants.append(forms)
    out = []
    for forms in variants:
        for f in forms:
            out.append(f)
    # «х у й» и «п и з д а»: подряд идущие одиночные буквы склеиваем
    run = ""
    for w in words + [""]:
        if len(w) == 1 and w.isalpha():
            run += w
            continue
        if len(run) >= 3:
            out.append(run)
        run = ""
    return out


def find_violation(text: str, categories=("mat", "insult", "hate", "threat"), extra=(), allow=()):
    """-> (категория, слово) для первого найденного нарушения или None.

    extra: свои запрещённые слова сервера; allow: слова-исключения сервера.
    """
    allowed = {collapse(clean(a)) for a in allow} | SAFE
    extra_set = {collapse(clean(e)) for e in extra if e.strip()}
    cleaned = clean(text)
    for raw in tokens(text):
        word = collapse(raw)
        if not word or word in allowed or raw in allowed:
            continue
        if word in extra_set:
            return "custom", raw
        for category in categories:
            patterns = _WORDS_RU.get(category, []) if _CYR.search(word) else _WORDS_LAT.get(category, [])
            for pattern in patterns:
                if pattern.fullmatch(word):
                    return category, raw
    flat = " ".join(_WORD.findall(cleaned))
    for category in categories:
        for pattern in _PHRASES.get(category, []):
            found = pattern.search(flat)
            if found:
                return category, found.group(0)
    return None


def mask(word: str) -> str:
    """Скрывает слово в логе: первая буква и звёздочки."""
    word = word.strip()
    return word[:1] + "*" * max(2, len(word) - 1) if word else ""


def censor(text: str, word: str) -> str:
    """Закрывает найденное слово в тексте для лога."""
    if not word:
        return text
    return re.sub(re.escape(word), mask(word), text, flags=re.I)
